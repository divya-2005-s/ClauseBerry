"""Profile the raw ToS Radar dataset and write docs/dataset_report.md.

Read-only: the source CSVs in tos_radar_dataset/ are never modified.

Usage:  python -m pipeline.inspect_dataset
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATASET = ROOT / "tos_radar_dataset"
REPORT = ROOT / "docs" / "dataset_report.md"


def _md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def main() -> None:
    files = sorted(p for p in DATASET.iterdir() if p.is_file())
    out: list[str] = ["# Dataset inspection report", "",
                      "Generated by `python -m pipeline.inspect_dataset` from the files in "
                      "`tos_radar_dataset/` (read-only).", "", "## Files", ""]
    out.append(_md_table(pd.DataFrame(
        [{"file": p.name, "bytes": p.stat().st_size,
          "sha256 (first 12)": hashlib.sha256(p.read_bytes()).hexdigest()[:12]} for p in files])))

    readme = DATASET / "README.md"
    if readme.exists():
        out += ["", "## Provenance and licence (from the dataset README)", "",
                "> " + readme.read_text(encoding="utf-8").strip().replace("\n", "\n> ")]

    versions = pd.read_csv(DATASET / "policy_versions.csv")
    changes = pd.read_csv(DATASET / "policy_changes.csv")
    latest = pd.read_csv(DATASET / "latest_policies.csv")

    for name, df in [("policy_versions.csv", versions), ("policy_changes.csv", changes),
                     ("latest_policies.csv", latest)]:
        out += ["", f"## `{name}`", "", f"Rows: **{len(df):,}**, columns: **{df.shape[1]}**", ""]
        schema = pd.DataFrame({"column": df.columns, "dtype": [str(t) for t in df.dtypes],
                               "nulls": df.isna().sum().values,
                               "example": [str(df[c].dropna().iloc[0])[:60].replace("\n", " ").replace("|", "/")
                                           if df[c].notna().any() else "" for c in df.columns]})
        out.append(_md_table(schema))

    out += ["", "## Coverage", "",
            f"- Services: **{versions.service.nunique()}** "
            f"({', '.join(sorted(versions.service.unique()))})",
            f"- Document types: {', '.join(sorted(versions.document_type.unique()))}",
            f"- Version dates: **{versions.version_date.min()} → {versions.version_date.max()}**",
            f"- Change dates: {changes.change_date.min()} → {changes.change_date.max()}", ""]
    cov = (versions.groupby(["service", "document_type"]).version_date
           .agg(first="min", last="max", versions="count").reset_index())
    out.append(_md_table(cov))

    out += ["", "## Data-quality findings", ""]
    dup_ts = versions.duplicated(["service", "document_type", "version_datetime"], keep=False)
    dup_exact = versions.duplicated(["service", "document_type", "version_datetime", "text"])
    dup_text = versions.duplicated(["service", "document_type", "text"])
    tiny = versions[versions.word_count < 50]
    small_changes = ((changes.lines_added + changes.lines_removed) <= 2).sum()
    out += [
        f"- Rows sharing a (service, document, timestamp): **{int(dup_ts.sum())}** "
        f"({', '.join(sorted(versions[dup_ts].service.unique()))}). These carry *different* texts "
        "captured at the same instant (regional / A-B variants), so they are kept as distinct versions.",
        f"- Exact duplicate rows (same timestamp and text): **{int(dup_exact.sum())}** — dropped on load.",
        f"- Versions whose full text is identical to an earlier version of the same document: "
        f"**{int(dup_text.sum())}** — this signals variants alternating back and forth "
        "(e.g. TikTok), which the change detector treats as reverts, not new changes.",
        f"- Suspiciously short captures (< 50 words): **{len(tiny)}** "
        + (f"({'; '.join(f'{r.service} {r.document_type} {r.version_date}: {r.word_count} words' for r in tiny.itertuples())}). "
           if len(tiny) else "")
        + "Treated as probable capture failures rather than real policy rewrites.",
        f"- Precomputed changes with ≤ 2 changed lines: **{int(small_changes)}** of {len(changes):,}; most are "
        "formatting / asset-URL noise (e.g. rotating image revision ids).",
        f"- Changes with no added text: {int(changes.added_text.isna().sum())}; with no removed text: "
        f"{int(changes.removed_text.isna().sum())}.",
        "- `Twitter` (2022-09 → 2023-10) and `X` (2024-02 →) are separate services in the source. "
        "ClauseBerry keeps them separate (matching the archive) and notes the rename in the UI.",
        "- `Mastodon` has a single version per document, so no change history is available.",
        "- Coverage per service varies widely (Facebook: 603 versions; Moltbook: 4). The first time a "
        "clause is observed is therefore *not* necessarily when the practice began.",
    ]

    kw = {"train": "train", "artificial intelligence": "artificial intelligence",
          "machine learning": "machine learning", "generative": "generative",
          "large language model": "large language model"}
    rows = [{"term": k, "versions mentioning": int(versions.text.str.contains(v, case=False).sum()),
             "changes adding it": int(changes.added_text.fillna("").str.contains(v, case=False).sum())}
            for k, v in kw.items()]
    out += ["", "## AI-related vocabulary (raw substring counts, not classifications)", "", _md_table(pd.DataFrame(rows))]
    out += ["", "## How ClauseBerry uses the files", "",
            "- `policy_versions.csv` is the source of truth: loaded into `policy_versions`, then diffed "
            "by `pipeline.clean_changes` with noise normalisation.",
            "- `policy_changes.csv` is loaded into `source_changes` for provenance and cross-checking; "
            "ClauseBerry's own `policy_changes` table is recomputed from versions.",
            "- `latest_policies.csv` is cross-checked against the latest version per document.", ""]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
