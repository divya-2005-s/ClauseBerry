import { Bot, CircleAlert, CircleCheck, CircleDot, ShieldAlert, Sparkles, TriangleAlert, Wand2 } from "lucide-react"

import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip"
import { cn } from "@/lib/utils"
import type { AiStatus } from "@/lib/types"

export const RISK_LABELS: Record<number, string> = { 1: "Minimal", 2: "Low", 3: "Medium", 4: "High", 5: "Critical" }

const RISK_STYLE: Record<number, string> = {
  1: "bg-muted text-muted-foreground border-border",
  2: "bg-[color-mix(in_oklab,var(--risk-1)_14%,transparent)] text-foreground border-[color-mix(in_oklab,var(--risk-1)_45%,transparent)]",
  3: "bg-[color-mix(in_oklab,var(--risk-3)_14%,transparent)] text-foreground border-[color-mix(in_oklab,var(--risk-3)_45%,transparent)]",
  4: "bg-[color-mix(in_oklab,var(--risk-4)_16%,transparent)] text-foreground border-[color-mix(in_oklab,var(--risk-4)_55%,transparent)]",
  5: "bg-[color-mix(in_oklab,var(--critical)_16%,transparent)] text-foreground border-[color-mix(in_oklab,var(--critical)_55%,transparent)]",
}
const RISK_ICON = { 1: CircleCheck, 2: CircleDot, 3: CircleAlert, 4: TriangleAlert, 5: ShieldAlert } as const
const RISK_ICON_COLOR: Record<number, string> = {
  1: "text-success",
  2: "text-[var(--risk-2)]",
  3: "text-[var(--risk-3)]",
  4: "text-[var(--risk-4)]",
  5: "text-critical",
}

/** Risk is never colour-only: icon + label + score. */
export function RiskBadge({ score, className, showScore = true }: { score: number | null | undefined; className?: string; showScore?: boolean }) {
  if (!score) return <span className="text-xs text-muted-foreground">Not analysed</span>
  const Icon = RISK_ICON[score as keyof typeof RISK_ICON]
  return (
    <span
      className={cn(
        "inline-flex h-6 items-center gap-1 rounded-full border px-2 text-xs font-medium whitespace-nowrap",
        RISK_STYLE[score],
        className,
      )}
    >
      <Icon className={cn("size-3.5", RISK_ICON_COLOR[score])} aria-hidden />
      {RISK_LABELS[score]}
      {showScore && <span className="text-muted-foreground tabular-nums">· {score}/5</span>}
    </span>
  )
}

export function CategoryBadge({ label }: { label?: string | null }) {
  if (!label) return null
  return (
    <span className="inline-flex h-6 items-center rounded-full bg-secondary px-2 text-xs font-medium text-secondary-foreground whitespace-nowrap">
      {label}
    </span>
  )
}

const AI_STYLE: Record<AiStatus["status"], { cls: string; short: string }> = {
  explicit_training: { cls: "bg-coral-soft text-foreground border-[color-mix(in_oklab,var(--coral)_45%,transparent)]", short: "Training language" },
  training_removed: { cls: "bg-muted text-foreground border-border", short: "Training language removed" },
  ai_provider_sharing: { cls: "bg-secondary text-secondary-foreground border-transparent", short: "AI provider sharing" },
  general_ai: { cls: "bg-muted text-muted-foreground border-transparent", short: "AI mentioned" },
  none: { cls: "bg-transparent text-muted-foreground border-dashed border-border", short: "No AI language" },
}

export function AiStatusBadge({ status, compact = false }: { status?: AiStatus | null; compact?: boolean }) {
  const s = status?.status ?? "none"
  const style = AI_STYLE[s]
  const Icon = s === "explicit_training" ? Sparkles : s === "none" ? Bot : Wand2
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn("inline-flex h-6 items-center gap-1 rounded-full border px-2 text-xs font-medium whitespace-nowrap", style.cls)}
        >
          <Icon className={cn("size-3.5", s === "explicit_training" && "text-coral")} aria-hidden />
          {compact ? style.short : status?.label ?? style.short}
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-64">
        Based on sentence-level pattern matching in the latest archived policy text. Mentioning AI is not evidence
        that user data trains models.
      </TooltipContent>
    </Tooltip>
  )
}

export function AnalyzerBadge({ analyzer, model }: { analyzer?: string | null; model?: string | null }) {
  if (!analyzer) return null
  const llm = analyzer === "llm"
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className="inline-flex h-6 items-center gap-1 rounded-full border border-dashed px-2 text-[11px] font-medium text-muted-foreground whitespace-nowrap"
        >
          {llm ? <Sparkles className="size-3" aria-hidden /> : <Wand2 className="size-3" aria-hidden />}
          {llm ? "AI summary" : "Rule-based"}
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-64">
        {llm
          ? `Generated by ${model}. Automated analysis — verify against the source text. Not legal advice.`
          : "Produced by ClauseBerry's documented rule-based analyzer because no language model is configured. Not legal advice."}
      </TooltipContent>
    </Tooltip>
  )
}
